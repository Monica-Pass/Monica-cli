//! Embedded, typed catalogs. Keep both translations and named placeholders
//! together when adding a message; tests check catalog completeness.
use super::Language;

macro_rules! catalog {
    ($($key:ident => [$en:literal, $zh:literal],)*) => {
        #[derive(Clone, Copy, Debug, PartialEq, Eq)]
        pub enum Message { $($key,)* }

        impl Language {
            pub const fn text(self, message: Message) -> &'static str {
                match (self, message) {
                    $((Self::En, Message::$key) => $en,
                      (Self::ZhCn, Message::$key) => $zh,)*
                }
            }
        }
        impl Message {
            #[cfg(test)]
            pub(super) const ALL: &'static [Self] = &[$(Self::$key,)*];
        }
    };
}

